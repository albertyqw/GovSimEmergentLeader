"""B9/B10 compare fixed-state original requests and save prompt diffs."""

import difflib
import hashlib
import json
import os
import subprocess
import sys
import tarfile
import tempfile
from pathlib import Path

from simulation import interventions


ROOT = Path(__file__).resolve().parents[1]
CONDITIONS = ("replica_N8", "baseline_N8", "values_N8", "stakes_N8", "coord_N16", "coord_N32")


def main():
    golden = ROOT / "tests/golden"
    golden.mkdir(exist_ok=True)
    environment = {**os.environ, "WANDB_DISABLED": "true",
                   "PYTHONPATH": str(ROOT), "HF_HOME": "/private/tmp/emergent-leadership-hf-cache"}
    with tempfile.TemporaryDirectory() as temporary:
        temporary = Path(temporary)
        reference = temporary / "original"
        reference.mkdir()
        archive = temporary / "original.tar"
        with archive.open("wb") as output:
            subprocess.run(["git", "archive", "8cf0aba"], cwd=ROOT, stdout=output, check=True)
        with tarfile.open(archive) as source:
            source.extractall(reference, filter="data")
        # Only the already-approved startup repair is applied to the reference.
        file = reference / "simulation/persona/persona.py"
        text = file.read_text().replace("        embedding_model: EmbeddingModel,\n", "")
        text = text.replace("model, model_framework, self.memory, embedding_model\n", "model, model_framework, self.memory\n")
        text = text.replace("model, model_framework, self.memory, embedding_model, self.cfg.store", "model, model_framework, self.memory, self.cfg.store")
        file.write_text(text)
        original = temporary / "original_requests.json"
        child_code = "import sys; sys.path.insert(0, sys.argv.pop(1)); from tools.fixture_run import main; main()"
        subprocess.run([sys.executable, "-c", child_code, str(reference), "original", str(original), str(temporary / "original_raw")],
                       cwd=reference, env=environment, check=True)
        original_text = original.read_text()
        control = temporary / "unmodified.json"
        subprocess.run([sys.executable, "-m", "tools.fixture_run", "unmodified", str(control), str(temporary / "unmodified_raw")],
                       cwd=ROOT, env=environment, check=True)
        if control.read_text() != original_text:
            raise AssertionError("Disabled paper/intervention overrides changed the original request path")
        (golden / "original_path.diff").write_text("")
        summary = {"original_path": {"requests": len(json.loads(original_text)),
                    "sha256": hashlib.sha256(original_text.encode()).hexdigest(),
                    "diff_file": "tests/golden/original_path.diff", "matches_original": True}}
        excerpts = {}
        for condition in CONDITIONS:
            output = temporary / f"{condition}.json"
            subprocess.run([sys.executable, "-m", "tools.fixture_run", condition, str(output), str(temporary / f"{condition}_raw")],
                           cwd=ROOT, env=environment, check=True)
            current = output.read_text()
            prompts = [message["content"] for row in json.loads(current) for message in row["request"]["messages"]]
            markers = {
                "replica_N8": "There are 8 fishermen",
                "baseline_N8": "Here is the monthly fishing report:",
                "values_N8": "You are a fisherman in the fishing community",
                "stakes_N8": "[months remaining:",
                "coord_N16": "carrying capacity of 200",
                "coord_N32": "carrying capacity of 400",
            }
            marker = markers[condition]
            prompt = next((text for text in prompts if marker in text), prompts[0])
            position = prompt.find(marker)
            excerpts[condition] = prompt[max(0, position - 30):position + 650]
            for row in json.loads(current):
                request = row["request"]
                fresh = request["messages"][-1]["content"].startswith("Rating (1 to 10):")
                if request["max_tokens"] != (1000 if fresh else 16000):
                    raise AssertionError("Study payload has the wrong generation/rating token cap")
            diff = "".join(difflib.unified_diff(original_text.splitlines(keepends=True), current.splitlines(keepends=True),
                                              fromfile="8cf0aba (approved startup repair only)", tofile=condition))
            (golden / f"{condition}.diff").write_text(diff)
            summary[condition] = {"requests": len(json.loads(current)), "sha256": hashlib.sha256(current.encode()).hexdigest(),
                                  "diff_file": f"tests/golden/{condition}.diff", "matches_original": not diff}
        (golden / "summary.json").write_text(json.dumps(summary, indent=2) + "\n")
        sections = ["# Prompt fidelity evidence\n\nGenerated by `python -m tools.build_fidelity` using one-cycle deterministic transport stubs. "
                    "These are rendered prompts, not paid model responses. The pinned reference receives only the approved "
                    "constructor repair. A fixed original opener controls the comparison state. Full sorted requests and canned "
                    "responses are hashed; unified diffs cover every request type. The disabled-override original path matches byte for byte. "
                    "All study conditions, including replica, use the approved common paper definitions, ten-entry recall, aligned prompts "
                    "and 16000/1000 token caps. These are disclosed exceptions to the pinned source. Live routing and the user-approved common neutral study amendment (explicit group size, no scripted leadership cues, keyed uniform invalid-nomination fallback) are also approved exceptions.\n"]
        locations = {
            "PARTICIPANT_COUNT_TEMPLATE": "simulation/persona/cognition/utils.py:get_sytem_prompt_v3",
            "ANNOUNCER_TEMPLATE": "simulation/persona/cognition/converse.py",
            "VALUES_AGENDA": "simulation/conf/experiment/values_N8*.yaml; simulation/persona/cognition/utils.py",
            "STAKES_TAG_FORMAT": "simulation/persona/cognition/utils.py:render_name",
            "STAKES_INSTRUCTION": "simulation/persona/cognition/utils.py:get_sytem_prompt_v3",
            "ELICITATION_PROMPT": "simulation/measurement_prompts.py:measure",
            "ELICITATION_PROMPT_FINAL_MONTH": "simulation/measurement_prompts.py:measure",
            "PERCEIVED_LEADERSHIP_PROMPT": "simulation/measurement_prompts.py:measure",
        }
        for name, location in locations.items():
            sections.append(f"\n## B5 {name}\n\nExact specification text, stored in `simulation/interventions.py`; rendered by `{location}`. "
                            f"The character-equality test checks it against METHODS.md.\n\n```text\n{getattr(interventions, name)}\n```\n")
        sections.append("\n## Condition excerpts and complete diffs\n\nAll study arms remove scripted mayor/leader cues under the common neutral amendment. "
                        "Values adds focal goals and paper-aligned SVO text with privacy. All arms share paper-aligned honesty, system-text correction, ten-entry recall and 16000/1000 caps. Stakes adds current tags and the household instruction; "
                        "its resolver strips tags before identity matching. Coordination scales lake numbers and participant lists. "
                        "Private instruments reuse the original prefix and add the approved public-report context. "
                        "Task-specific summary/reflection/limit-extraction prompts remain unchanged; common general-system changes and stakes name placeholders are explicitly allowlisted.\n")
        for condition in CONDITIONS:
            item = summary[condition]
            sections.append(f"\n### {condition}\n\n{item['requests']} requests; SHA-256 `{item['sha256']}`. "
                            f"Full diff: [{condition}.diff]({item['diff_file']}).\n\n```text\n{excerpts[condition]}\n```\n")
        (ROOT / "FIDELITY.md").write_text("".join(sections))
        print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
